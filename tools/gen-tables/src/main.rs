// Generates src/tables/{trig,drft,window}.rs from the lookup tables the
// vendored libvorbis 1.3.7 builds at runtime (mdct_init, drft_init) or
// ships as literals (window.c vwin*).
//
// Nothing is recomputed in Rust: every value is copied bit-for-bit from the
// raw dumps written by `tools/oracle-encoder/dsp_oracle tables <dir>`
// (built with -O0 -ffp-contract=off by build_dsp_oracle.sh). Recomputing
// cos/sin in Rust would tie the tables to the host libm; the C dumps are
// the ground truth by construction.
//
// Usage (from the repo root):
//     ./tools/oracle-encoder/build_dsp_oracle.sh
//     ./tools/oracle-encoder/dsp_oracle tables /tmp/oxivorbis-dsp-tables
//     cargo run -p gen-tables [-- <dir>]          # default /tmp/oxivorbis-dsp-tables
//     cargo fmt --all
// or simply `just regen-tables`.

use std::fmt::Write as _;

const DEFAULT_DIR: &str = "/tmp/oxivorbis-dsp-tables";

/// MDCT sizes: 128 (envelope), 256/2048 (q0..q10 blocks), 512/4096 (q-1).
const MDCT_SIZES: [usize; 5] = [2048, 256, 128, 512, 4096];
/// psy FFT sizes (= blocksizes).
const DRFT_SIZES: [usize; 4] = [2048, 256, 512, 4096];
/// Window half-tables (vwin for blocksize bs holds bs/2 floats).
const WIN_SIZES: [usize; 4] = [256, 2048, 512, 4096];

/// Format an f32 as a Rust literal that round-trips exactly.
fn fmt_f32(v: f32) -> String {
    assert!(v.is_finite(), "non-finite table value {v:?}");
    let s = format!("{:.9e}", v);
    let reparsed: f32 = s.parse().unwrap();
    assert_eq!(
        v.to_bits(),
        reparsed.to_bits(),
        "round-trip failed for {v:?}"
    );
    format!("{s}_f32")
}

fn read_bytes(dir: &str, name: &str, expect_len: usize) -> Vec<u8> {
    let path = format!("{dir}/{name}");
    let bytes = std::fs::read(&path).unwrap_or_else(|_| {
        panic!("missing {path}; run `tools/oracle-encoder/dsp_oracle tables {dir}` first")
    });
    assert_eq!(bytes.len(), expect_len, "{path} size mismatch");
    bytes
}

fn load_f32(dir: &str, name: &str, count: usize) -> Vec<f32> {
    read_bytes(dir, name, count * 4)
        .chunks_exact(4)
        .map(|c| f32::from_le_bytes([c[0], c[1], c[2], c[3]]))
        .collect()
}

fn load_i32(dir: &str, name: &str, count: usize) -> Vec<i32> {
    read_bytes(dir, name, count * 4)
        .chunks_exact(4)
        .map(|c| i32::from_le_bytes([c[0], c[1], c[2], c[3]]))
        .collect()
}

fn write_array<T>(out: &mut String, decl: &str, ty: &str, vals: &[T], fmt: impl Fn(&T) -> String) {
    writeln!(out, "pub static {decl}: [{ty}; {}] = [", vals.len()).unwrap();
    for v in vals {
        writeln!(out, "    {},", fmt(v)).unwrap();
    }
    out.push_str("];\n\n");
}

fn header(regen: &str) -> String {
    format!(
        "// AUTO-GENERATED by tools/gen-tables from libvorbis 1.3.7 runtime dumps. Do not edit. \
         Regenerate via '{regen}'.\n#![allow(clippy::excessive_precision)]\n\n"
    )
}

fn finish(path: &str, mut s: String) {
    while s.ends_with("\n\n") {
        s.pop();
    }
    std::fs::write(path, s).unwrap_or_else(|e| panic!("failed to write {path}: {e}"));
    eprintln!("Wrote {path}");
}

fn main() {
    let dir = std::env::args()
        .nth(1)
        .unwrap_or_else(|| DEFAULT_DIR.to_string());

    // --- MDCT (mdct_init): trig (n + n/4), bitrev (n/4), scale -----------------
    let mut out = header("just regen-tables");
    for n in MDCT_SIZES {
        let trig = load_f32(&dir, &format!("mdct_{n}_trig.bin"), n + n / 4);
        let bitrev = load_i32(&dir, &format!("mdct_{n}_bitrev.bin"), n / 4);
        let scale = load_f32(&dir, &format!("mdct_{n}_scale.bin"), 1)[0];
        write_array(&mut out, &format!("TRIG_{n}"), "f32", &trig, |v| {
            fmt_f32(*v)
        });
        write_array(&mut out, &format!("BITREV_{n}"), "u32", &bitrev, |v| {
            u32::try_from(*v).expect("negative bitrev").to_string()
        });
        writeln!(out, "pub static SCALE_{n}: f32 = {};\n", fmt_f32(scale)).unwrap();
    }
    finish("src/tables/trig.rs", out);

    // --- Real FFT (drft_init) -----------------------------------------------
    // trigcache is 3n floats: [0..n) is scratch (`ch`) for drft_forward,
    // drfti1 fills only [n..2n) of the twiddle region `wa = trigcache + n`,
    // and [2n..3n) stays zero. We embed just the populated n-float `wa`.
    let mut out = header("just regen-tables");
    for n in DRFT_SIZES {
        let trig = load_f32(&dir, &format!("drft_{n}_trig.bin"), 3 * n);
        assert!(
            trig[..n]
                .iter()
                .chain(&trig[2 * n..])
                .all(|v| v.to_bits() == 0),
            "drft n={n}: expected trigcache[0..n) and [2n..3n) to be zero"
        );
        let split = load_i32(&dir, &format!("drft_{n}_split.bin"), 32);
        write_array(
            &mut out,
            &format!("DRFT_WA_{n}"),
            "f32",
            &trig[n..2 * n],
            |v| fmt_f32(*v),
        );
        write_array(&mut out, &format!("DRFT_SPLIT_{n}"), "i32", &split, |v| {
            v.to_string()
        });
    }
    finish("src/tables/drft.rs", out);

    // --- Windows (window.c vwin literals) -------------------------------------
    // The window.c literals differ by hundreds of ULPs from formula-generated
    // values at the window edge — critical for ramp/DC-heavy MDCT bin 0.
    let mut out = header("just regen-tables");
    let halves: Vec<(usize, Vec<f32>)> = WIN_SIZES
        .iter()
        .map(|&bs| (bs, load_f32(&dir, &format!("vwin_{bs}.bin"), bs / 2)))
        .collect();
    // Full symmetric windows for the Q5 sizes, used only by unit tests.
    for &bs in &[2048usize, 256] {
        let half = &halves.iter().find(|(b, _)| *b == bs).unwrap().1;
        let mut full = vec![0.0f32; bs];
        for i in 0..bs / 2 {
            full[i] = half[i];
            full[bs - 1 - i] = half[i];
        }
        out.push_str("#[cfg(test)]\n");
        write_array(&mut out, &format!("SIN_WINDOW_{bs}"), "f32", &full, |v| {
            fmt_f32(*v)
        });
    }
    for (bs, half) in &halves {
        write_array(&mut out, &format!("WIN_HALF_{bs}"), "f32", half, |v| {
            fmt_f32(*v)
        });
    }
    finish("src/tables/window.rs", out);
}
